def build_results(par, prob, gen, unserved, spill):
    """Assemble the hourly results table, including the clearing price."""

    PLANTS, HOURS = par["PLANTS"], par["HOURS"]
    avail, mc_vec, demand_vec = par["avail"], par["mc_vec"], par["demand_vec"]

    # Pull the solution out of the solver once, into a (n_plants, n_hours)
    # array laid out the same way as `avail`. Everything below is then plain
    # array arithmetic. `or 0.0` guards against a None from an unused
    # variable.
    output = np.array(
        [[gen[p][t].value() or 0.0 for t in HOURS] for p in PLANTS],
        dtype=float)

    unserved_vec = np.array([unserved[t].value() or 0.0 for t in HOURS], dtype=float)
    spill_vec = np.array([spill[t].value() or 0.0 for t in HOURS], dtype=float)

    # Ramp quantities, recomputed from the generation profile rather than read
    # from the LP's ramp variables. Those variables are bounded below by the
    # true movement but not pinned to it, so a plant with a zero ramp premium
    # can leave them anywhere up to its rate limit without changing the
    # objective. The generation profile is the only honest source. Column 0 is
    # zero: hour 1 has no predecessor, so nothing moved into it.
    delta = np.zeros_like(output)
    delta[:, 1:] = output[:, 1:] - output[:, :-1]
    ramp_up_arr = np.maximum(0.0, delta)
    ramp_down_arr = np.maximum(0.0, -delta)

    # The premium alone, not the cost of the ramped energy. The fuel and VOM
    # underneath a ramped MWh are already counted in Production Cost, so
    # adding them here would double count against the LP objective.
    ramp_cost_vec = par["ramp_cost_vec"]
    ramp_cost_hourly = ramp_cost_vec @ (ramp_up_arr + ramp_down_arr)

    # Clearing price: the dual of the energy balance, which is what one more
    # MWh in this hour would cost the system. With ramping in the objective
    # this is no longer equal to any single plant's marginal cost, because an
    # extra MWh here also changes what it costs to serve the neighbouring
    # hours. See "Prices" in the module docstring.
    price = []
    for t in HOURS:
        constraint = prob.constraints.get("balance_{}".format(t))
        pi = constraint.pi if constraint is not None else None
        price.append(float(pi) if pi is not None else np.nan)
    price = np.array(price, dtype=float)

    # Diagnostic, not a price: the marginal cost of the most expensive plant
    # actually generating. This is the old merit-order clearing price under
    # the name of what it really measures. Non-running plants are masked to
    # -inf rather than 0 so that a negative marginal cost could still be the
    # highest; hours with nothing running fall back to 0.0.
    running = output > TOL
    masked_mc = np.where(running, mc_vec[:, None], -np.inf)
    highest_running = np.where(running.any(axis=0), masked_mc.max(axis=0), 0.0)

    # Curtailment: profiled renewable energy that was available but not taken,
    # because demand was already met by cheaper or equal output. Distinct from
    # spill, which is energy that was generated and then thrown away.
    curtailed = np.maximum(0.0, avail - output)[par["profiled_mask"]].sum(axis=0)

    # Column order here is the column order of the CSV, so keep the generation
    # block ahead of the availability block. Availability is written out as
    # well as generation, because a profiled plant sitting at its resource
    # limit is at capacity even though it is far below nameplate. Anything
    # reading these results needs the hourly limit to tell "maxed out" from
    # "part loaded".
    columns = {"Hour": HOURS, "Demand (MWh)": demand_vec}
    for i, p in enumerate(PLANTS):
        columns["{} (MWh)".format(p)] = output[i]
    for i, p in enumerate(PLANTS):
        columns["{} Available (MWh)".format(p)] = avail[i]
    columns["Clearing Price ($/MWh)"] = price
    columns["Highest Running Cost ($/MWh)"] = highest_running
    columns["Production Cost ($)"] = mc_vec @ output
    columns["Ramp Up (MWh)"] = ramp_up_arr.sum(axis=0)
    columns["Ramp Down (MWh)"] = ramp_down_arr.sum(axis=0)
    columns["Ramp Cost ($)"] = ramp_cost_hourly
    columns["Market Cost ($)"] = price * demand_vec
    columns["Unserved Energy (MWh)"] = unserved_vec
    columns["Unserved Cost ($)"] = VOLL * unserved_vec
    columns["Spill (MWh)"] = spill_vec
    columns["Spill Cost ($)"] = SPILL_COST * spill_vec
    columns["Curtailment (MWh)"] = curtailed

    if np.isnan(price).any():
        print("  WARNING: the solver returned no dual for {} of {} hours, so "
              "the clearing price is missing there.\n"
              .format(int(np.isnan(price).sum()), len(HOURS)))

    return pd.DataFrame(columns)



def build_summary(par, results):
    """Per-plant totals: energy, capacity factor, hours running, cost."""

    n_hours = len(par["HOURS"])
    rows = []

    for p in par["PLANTS"]:
        series = results["{} (MWh)".format(p)]
        total = series.sum()
        max_possible = par["capacity"][p] * n_hours

        # Energy the plant could have produced given its resource. For a
        # thermal plant this is just nameplate around the clock; for wind and
        # solar it is limited by the hourly profile.
        is_profiled = p in par["profiled"]
        available = sum(par["availability"][p][t] for t in par["HOURS"])

        # Curtailment only means something for a profiled plant: energy the
        # resource offered but the dispatch did not take. Idle thermal
        # capacity is not curtailment, it is simply not being called on.
        curtailed = max(0.0, available - total) if is_profiled else 0.0

        # Movement, from the generation profile. Hour 1 has no predecessor so
        # the first difference is dropped rather than counted as a ramp.
        delta = series.to_numpy(dtype=float)[1:] - series.to_numpy(dtype=float)[:-1]
        ramp_up = float(np.maximum(0.0, delta).sum())
        ramp_down = float(np.maximum(0.0, -delta).sum())

        # A plant is last in the stack in an hour when it is running and its
        # marginal cost is the highest of anything running. Under ramping the
        # clearing price is the dual and no longer equals any plant's marginal
        # cost, so this is matched against the Highest Running Cost diagnostic
        # instead. It counts who was last in the merit order, which is not the
        # same as who set the price.
        is_running = series > TOL
        is_last = (results["Highest Running Cost ($/MWh)"]
                   - par["marginal_cost"][p]).abs() < 1e-6
        hours_last_in_stack = int((is_running & is_last).sum())

        rows.append({
            "Plant": p,
            "Technology": par["technology"][p],
            "Fuel": par["plant_fuel"][p],
            "Capacity (MW)": par["capacity"][p],
            "Profiled": is_profiled,
            "Marginal Cost ($/MWh)": par["marginal_cost"][p],
            "Ramp Rate (MW/hr)": par["ramp_rate"][p],
            "Ramping Efficiency (MWh/MWhTh)": par["ramp_efficiency"][p],
            "Ramp Premium ($/MWh)": par["ramp_cost"][p],
            "Total Generation (MWh)": total,
            "Available Energy (MWh)": available,
            "Curtailed (MWh)": curtailed,
            "Curtailment (%)": (100.0 * curtailed / available
                                if is_profiled and available > 0 else 0.0),
            "Share of Demand (%)": 100.0 * total / results["Demand (MWh)"].sum(),
            "Capacity Factor (%)": 100.0 * total / max_possible if max_possible else 0.0,
            "Availability Factor (%)": (100.0 * available / max_possible
                                        if max_possible else 0.0),
            "Hours Running": int(is_running.sum()),
            "Hours Last in Stack": hours_last_in_stack,
            "Total Ramp Up (MWh)": ramp_up,
            "Total Ramp Down (MWh)": ramp_down,
            # The premium only, matching the results file, so that summing
            # this column reproduces the objective's ramp term exactly.
            "Ramp Cost ($)": par["ramp_cost"][p] * (ramp_up + ramp_down),
            # Fuel and VOM only, deliberately excluding ramp cost, so that the
            # four components of the objective stay separable.
            "Production Cost ($)": total * par["marginal_cost"][p],
        })

    return pd.DataFrame(rows).sort_values("Marginal Cost ($/MWh)").reset_index(drop=True)


