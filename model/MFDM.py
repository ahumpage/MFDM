BASE_DIR = Path(__file__).resolve().parent          # model/
REPO_ROOT = BASE_DIR.parent

# Inputs are read from inputs/ and results are written to results/, both at
# the repo root, so the model folder holds only code.
INPUTS_DIR = REPO_ROOT / "inputs"
RESULTS_DIR = REPO_ROOT / "results"

PLANTS_FILE = INPUTS_DIR / "plants.csv"
FUEL_FILE = INPUTS_DIR / "fuel.csv"
DEMAND_FILE = INPUTS_DIR / "demand.csv"
PROFILE_FILE = INPUTS_DIR / "profiles.csv"


# Generation below this is treated as "not running" when finding the marginal
# plant, so that solver round-off does not set the price.
TOL = 1e-6

# Value of Lost Load: what an hour of unmet demand is worth to the people who
# go without. Demand the fleet cannot cover is priced at this rather than
# making the model infeasible. 8300 $/MWh is the low end of the European
# Commission JRC estimate for Greece; see docs/research/scarcity_pricing.md.
# It must stay well above the most expensive plant's marginal cost, otherwise
# the solver would rather shed load than run that plant.
VOLL = 8300.0

# What a MWh of spilled energy costs: energy that was generated because a
# plant could not ramp down fast enough, and then had to be thrown away.
#
# This must NOT be set to VOLL, even though spill is the mirror of unserved
# energy, because the two are not symmetric in cost. Shedding a MWh *removes*
# a MWh of generation, so it saves VOLL minus the plant's marginal cost.
# Dumping a MWh *requires* a MWh of extra generation, so it costs SPILL_COST
# plus that marginal cost. Set the two constants equal and shedding always
# comes out cheaper by twice the marginal cost, so the solver blacks out real
# demand rather than dump a surplus, and `spill` never leaves zero.
#
# 1000 $/MWh sits far above the most expensive plant's marginal cost, so spill
# stays firmly last in the stack and is never used as a cheap way to dodge
# generating, while staying far enough below VOLL that dumping surplus is
# always preferred to shedding load. It is a modelling constant chosen for
# those two properties, not a physical quantity, and is worth revisiting.
SPILL_COST = 1000.0

# Technologies whose output is limited by an hourly resource profile rather
# than being available at nameplate around the clock. The value is the token
# looked for in the profiles.csv column headers.
PROFILE_TECHNOLOGIES = {
    "Wind": "wind",
    "Solar": "solar",
}


# --------------------------------------------------------------------------
# Step 1 - load data
# --------------------------------------------------------------------------

def load_data():
    """Read the four input CSVs and return them as DataFrames."""
    for path in (PLANTS_FILE, FUEL_FILE, DEMAND_FILE, PROFILE_FILE):
        if not path.exists():
            raise FileNotFoundError("Could not find input file: {}".format(path))

    # keep_default_na=False so that Solar's fuel of "None" stays the literal
    # string "None" rather than becoming NaN.
    plants = pd.read_csv(PLANTS_FILE, keep_default_na=False)
    fuel = pd.read_csv(FUEL_FILE)
    demand = pd.read_csv(DEMAND_FILE)

    # profiles.csv has two header rows: a region row (",FRA,FRA") and a
    # series row ("hours,wind (won),solar (solEB)"). Read both, then flatten
    # to single names of the form "FRA wind (won)", keeping the region so
    # multi-region files stay unambiguous.
    profile = pd.read_csv(PROFILE_FILE, header=[0, 1])
    flat = []
    for region, series in profile.columns:
        region = "" if str(region).startswith("Unnamed") else str(region).strip()
        series = str(series).strip()
        flat.append("{} {}".format(region, series).strip())
    profile.columns = flat

    # Tidy up stray whitespace in the text columns.
    for df in (plants, fuel, demand):
        df.columns = [c.strip() for c in df.columns]
    for col in ("Plant", "Technology", "Fuel"):
        plants[col] = plants[col].astype(str).str.strip()
    fuel["Technology"] = fuel["Technology"].astype(str).str.strip()

    return plants, fuel, demand, profile


# --------------------------------------------------------------------------
# Steps 2 and 3 - sets and parameters
# --------------------------------------------------------------------------

def build_parameters(plants, fuel, demand, profile):
    """Turn the raw DataFrames into the sets and parameter dictionaries."""

    # --- sets ---
    PLANTS = list(plants["Plant"])
    HOURS = [int(h) for h in demand["Hour"]]
    check_hours(HOURS)

    # --- fuel prices ---
    #Anything not listed is free.
    fuel_price = dict(zip(fuel["Technology"], fuel["Fuel Price ($/MWhTh)"].astype(float)))

    def price_of(fuel_name):
        if fuel_name is None:
            return 0.0
        if str(fuel_name).strip().lower() in ("none", "nan", ""):
            return 0.0
        if fuel_name not in fuel_price:
            print("  note: no fuel price listed for '{}', treating as $0/MWhTh".format(fuel_name))
            return 0.0
        return fuel_price[fuel_name]

    # --- per plant parameters ---
    capacity = {}
    efficiency = {}
    vom = {}
    technology = {}
    plant_fuel = {}
    marginal_cost = {}
    ramp_rate = {}
    ramp_efficiency = {}
    ramp_cost = {}

    # Located by prefix rather than by exact header, because the ramping
    # efficiency column is currently mislabelled "Ramp_efficiency($/hr)" while
    # holding efficiencies in MWh/MWhTh. Matching on the prefix means renaming
    # it to "Ramp_efficiency (MWh/MWhTh)" does not break the model.
    rate_col = find_column(plants, "Ramp_rate", "plants.csv")
    ramp_eff_col = find_column(plants, "Ramp_efficiency", "plants.csv")

    for _, row in plants.iterrows():
        p = row["Plant"]
        capacity[p] = float(row["Capacity (MW)"])
        efficiency[p] = float(row["Efficiency (MWh/MWhTh)"])
        vom[p] = float(row["VOM ($/MWh)"])
        technology[p] = row["Technology"]
        plant_fuel[p] = row["Fuel"]
        ramp_rate[p] = float(row[rate_col])
        ramp_efficiency[p] = float(row[ramp_eff_col])

        if efficiency[p] <= 0:
            raise ValueError("Plant {} has a non-positive efficiency".format(p))
        if ramp_efficiency[p] <= 0:
            raise ValueError(
                "Plant {} has a non-positive ramping efficiency".format(p))

        # A plant burns fuel less efficiently while it is moving than while it
        # is holding steady, so its ramping efficiency cannot be the better of
        # the two. If it were, the premium below would come out negative and
        # the solver would be paid to jiggle the plant up and down.
        if ramp_efficiency[p] > efficiency[p] + TOL:
            raise ValueError(
                "Plant {} has a ramping efficiency ({:.4f}) better than its "
                "ordinary efficiency ({:.4f}). Ramping is less efficient than "
                "steady running, not more, so this would make the ramp premium "
                "negative and pay the solver to move the plant about."
                .format(p, ramp_efficiency[p], efficiency[p]))
        if ramp_rate[p] < 0:
            raise ValueError("Plant {} has a negative ramp rate".format(p))

        # marginal cost = fuel cost / efficiency + VOM
        marginal_cost[p] = price_of(row["Fuel"]) / efficiency[p] + vom[p]

        # Ramp premium: what a moved MWh costs *over and above* a steady one.
        # VOM is not in here because it is charged on every MWh either way,
        # through marginal_cost; only the fuel burn differs while ramping.
        ramp_cost[p] = (price_of(row["Fuel"]) / ramp_efficiency[p]
                        - price_of(row["Fuel"]) / efficiency[p])

    # --- availability: nameplate capacity, scaled by an hourly resource
    # profile for the technologies that have one ---
    #
    # Built as a single (n_plants, n_hours) array. Rows for plants without a
    # profile stay at a factor of 1.0, i.e. available at nameplate around the
    # clock. The dict-of-dicts view is derived from the array below.
    profile_factors = build_profile_factors(profile, technology, HOURS)

    cap_vec = np.array([capacity[p] for p in PLANTS], dtype=float)
    mc_vec = np.array([marginal_cost[p] for p in PLANTS], dtype=float)
    profiled_mask = np.array([p in profile_factors for p in PLANTS], dtype=bool)

    factors_matrix = np.ones((len(PLANTS), len(HOURS)), dtype=float)
    for i, p in enumerate(PLANTS):
        factors = profile_factors.get(p)
        if factors is not None:
            factors_matrix[i] = [factors[t] for t in HOURS]

    avail = cap_vec[:, None] * factors_matrix

    ramp_rate_vec = np.array([ramp_rate[p] for p in PLANTS], dtype=float)
    ramp_cost_vec = np.array([ramp_cost[p] for p in PLANTS], dtype=float)

    # How much a plant is allowed to ramp down *beyond* its rate limit without
    # being charged, because its own resource collapsed underneath it.
    #
    # Without this a profiled plant is trapped by its own good hours. The
    # ramp-down limit puts a floor under a plant, gen[t] >= gen[t-1] - rate,
    # while the capacity constraint puts a ceiling over it, gen[t] <= avail[t].
    # When a wind or solar profile falls faster than the plant's ramp rate,
    # those two cannot both be satisfied at any positive output, so the only
    # way to obey them is to have been generating far below the resource in
    # the earlier hour.
    #
    # This is not infeasibility. The all-zeros dispatch always satisfies every
    # ramp constraint, so the LP can always retreat to it and price the demand
    # at VOLL. That is exactly the problem: the failure is silent and shows up
    # as an absurdly expensive answer rather than an error. Measured on a
    # fixture with a 500 MW solar farm limited to 10 MW/hr and a resource that
    # falls to zero after one hour, removing this allowance takes the
    # objective from $4,400 to $2,415,010 and leaves 58% of demand unserved,
    # because the plant may only use 10 MWh of its 500 MWh peak.
    #
    # Column 0 is zero because hour 1 has no predecessor and carries no ramp
    # constraint. Elsewhere the allowance is exactly the drop in availability,
    # so a plant is never penalised for a ramp down that the weather forced on
    # it, and never has to hold back in a good hour to protect itself.
    #
    # On the current inputs this never binds, because wind and solar both have
    # a ramp rate equal to their nameplate capacity. It exists so that editing
    # one number in plants.csv cannot silently wreck the dispatch.
    forced_down = np.zeros_like(avail)
    forced_down[:, 1:] = np.maximum(0.0, avail[:, :-1] - avail[:, 1:])

    # Legacy dict-of-dicts view, derived from `avail` so the two agree by
    # construction.
    availability = {p: dict(zip(HOURS, avail[i]))
                    for i, p in enumerate(PLANTS)}

    # --- demand ---
    demand_col = [c for c in demand.columns if c.lower().startswith("demand")][0]
    demand_vec = demand[demand_col].astype(float).to_numpy()
    demand_by_hour = dict(zip(HOURS, demand_vec))

    return {
        "PLANTS": PLANTS,
        "HOURS": HOURS,
        "capacity": capacity,
        "efficiency": efficiency,
        "vom": vom,
        "technology": technology,
        "plant_fuel": plant_fuel,
        "marginal_cost": marginal_cost,
        "ramp_rate": ramp_rate,
        "ramp_efficiency": ramp_efficiency,
        "ramp_cost": ramp_cost,
        "availability": availability,
        "profiled": set(profile_factors),
        "demand": demand_by_hour,
        # Array views, see "Array layout" in the module docstring.
        "avail": avail,
        "cap_vec": cap_vec,
        "mc_vec": mc_vec,
        "ramp_rate_vec": ramp_rate_vec,
        "ramp_cost_vec": ramp_cost_vec,
        "forced_down": forced_down,
        "demand_vec": demand_vec,
        "profiled_mask": profiled_mask,
    }


def find_column(df, prefix, filename):
    """Locate the one column of `df` whose name starts with `prefix`."""
    matches = [c for c in df.columns if c.strip().lower().startswith(prefix.lower())]
    if not matches:
        raise ValueError(
            "{} has no column starting with '{}'. Columns present: {}"
            .format(filename, prefix, ", ".join(df.columns)))
    if len(matches) > 1:
        raise ValueError(
            "{} has more than one column starting with '{}': {}. "
            "Column names must be unambiguous.".format(filename, prefix, matches))
    return matches[0]


def check_hours(HOURS):
    """Assert that HOURS is ascending, contiguous and free of duplicates.

    The hours are taken straight from the row order of demand.csv, which was
    harmless while every hour stood alone. The ramp constraints link each hour
    to the one before it in this list, so a gap, a duplicate or a stray sort
    order would quietly constrain the wrong pair of hours and the model would
    still solve, just against a horizon nobody intended.
    """
    if len(HOURS) < 1:
        raise ValueError("demand.csv contains no hours.")

    duplicates = sorted(set(h for h in HOURS if HOURS.count(h) > 1))
    if duplicates:
        raise ValueError(
            "demand.csv repeats {} hour(s), first {}. Each hour must appear "
            "once.".format(len(duplicates), duplicates[0]))

    breaks = [(HOURS[i - 1], HOURS[i]) for i in range(1, len(HOURS))
              if HOURS[i] != HOURS[i - 1] + 1]
    if breaks:
        a, b = breaks[0]
        raise ValueError(
            "demand.csv hours must be ascending and contiguous, but hour {} is "
            "followed by hour {} ({} such break(s) in total). Ramping links "
            "each hour to the previous row, so the horizon cannot have gaps or "
            "be out of order.".format(a, b, len(breaks)))


def build_profile_factors(profile, technology, HOURS):
    """Map each profiled plant to its hourly capacity factor.

    Returns {plant: {hour: factor}} containing only the plants whose
    technology has a matching column in profiles.csv. Plants absent from the
    result are treated as available at nameplate in every hour.
    """
    hour_col = profile.columns[0]
    available_hours = set(int(h) for h in profile[hour_col])

    missing = [t for t in HOURS if t not in available_hours]
    if missing:
        raise ValueError(
            "profiles.csv is missing {} of the {} hours in demand.csv "
            "(first missing: hour {}).".format(len(missing), len(HOURS), missing[0]))

    # Restrict profileto the modelled hours
    idx = profile[hour_col].astype(int)
    sub = profile.set_index(idx).loc[HOURS]

    factors = {}
    for plant, tech in technology.items():
        token = PROFILE_TECHNOLOGIES.get(tech)
        if token is None:
            continue

        matches = [c for c in profile.columns
                   if c is not hour_col and token in c.lower()]
        if not matches:
            print("  note: technology '{}' has no profile column in profiles.csv, "
                  "treating {} as always available".format(tech, plant))
            continue
        if len(matches) > 1:
            raise ValueError(
                "Technology '{}' matches more than one profile column: {}. "
                "Column names must be unambiguous.".format(tech, matches))

        series = sub[matches[0]].astype(float)
        lo, hi = float(series.min()), float(series.max())
        if lo < -TOL or hi > 1.0 + TOL:
            raise ValueError(
                "Profile column '{}' has values outside 0 to 1 (min {:.4f}, "
                "max {:.4f}). Expected capacity factors.".format(matches[0], lo, hi))

        factors[plant] = {t: float(v) for t, v in zip(HOURS, series.values)}

    return factors


def check_demand(par):
    "Flag suspicious demand values"
    zeros = [t for t in par["HOURS"] if par["demand"][t] <= 0.0]
    if zeros:
        shown = ", ".join(str(t) for t in zeros[:10])
        more = " and {} more".format(len(zeros) - 10) if len(zeros) > 10 else ""
        print("  WARNING: demand is zero or negative in {} hour(s): {}{}."
              .format(len(zeros), shown, more))
        print("           Check demand.csv. The model will dispatch nothing "
              "in those hours.\n")


def check_capacity_adequacy(par):
    "Warn before solving if demand exceeds everything the fleet can offer"
    short = []
    for t in par["HOURS"]:
        total = sum(par["availability"][p][t] for p in par["PLANTS"])
        if total < par["demand"][t] - TOL:
            short.append((t, par["demand"][t], total))

    if short:
        t, d, a = short[0]
        worst = max(short, key=lambda r: r[1] - r[2])
        print("  WARNING: demand exceeds available capacity in {} of {} hour(s)."
              .format(len(short), len(par["HOURS"])))
        print("           First is hour {}: demand {:,.2f} MWh vs {:,.2f} MW available."
              .format(t, d, a))
        print("           Worst is hour {}, short by {:,.2f} MW."
              .format(worst[0], worst[1] - worst[2]))
        print("           The shortfall will be priced at ${:,.2f}/MWh (VoLL). "
              "Check plants.csv and demand.csv.\n".format(VOLL))

# --------------------------------------------------------------------------
# Steps 4 to 7 - build and solve the LP
# --------------------------------------------------------------------------

def build_and_solve(par):
    "Build the dispatch LP, solve it, and return the model and variables."

    PLANTS, HOURS = par["PLANTS"], par["HOURS"]

    # Every hour but the first has a predecessor, and so a ramp constraint.
    # Hour 1 is where the fleet starts from nothing, free of charge.
    RAMP_HOURS = HOURS[1:]
    previous = {t: HOURS[i] for i, t in enumerate(HOURS[1:])}

    prob = pulp.LpProblem("Economic_Dispatch", pulp.LpMinimize)

    # --- Step 4: decision variables ---
    gen = pulp.LpVariable.dicts("gen", (PLANTS, HOURS), lowBound=0, cat="Continuous")

    # Unmet demand, one per hour. See "Scarcity" in the module docstring.
    unserved = pulp.LpVariable.dicts("unserved", HOURS, lowBound=0, cat="Continuous")

    # Surplus that had to be thrown away. See "Spill" in the module docstring.
    spill = pulp.LpVariable.dicts("spill", HOURS, lowBound=0, cat="Continuous")

    # Movement between adjacent hours, split into two non-negative variables
    # so that the absolute size of the move can be priced linearly. The upper
    # bound is the hard ramp rate limit, which is why no separate constraint
    # is needed for it.
    ramp_up = {p: {t: pulp.LpVariable(
        "rampup_{}_{}".format(p.replace(" ", "_"), t),
        lowBound=0, upBound=par["ramp_rate"][p]) for t in RAMP_HOURS} for p in PLANTS}
    ramp_down = {p: {t: pulp.LpVariable(
        "rampdown_{}_{}".format(p.replace(" ", "_"), t),
        lowBound=0, upBound=par["ramp_rate"][p]) for t in RAMP_HOURS} for p in PLANTS}

    # Cost-free headroom on the ramp-down limit, fixed by the collapse in the
    # plant's own availability. See `forced_down` in build_parameters.
    forced_down = {p: dict(zip(HOURS, par["forced_down"][i]))
                   for i, p in enumerate(PLANTS)}

    # --- Step 5: objective, total production cost, plus the cost of any
    # demand left unserved, any energy thrown away, and any movement ---
    prob += (
        pulp.lpSum(par["marginal_cost"][p] * gen[p][t] for p in PLANTS for t in HOURS)
        + pulp.lpSum(VOLL * unserved[t] for t in HOURS)
        + pulp.lpSum(SPILL_COST * spill[t] for t in HOURS)
        + pulp.lpSum(par["ramp_cost"][p] * (ramp_up[p][t] + ramp_down[p][t])
                     for p in PLANTS for t in RAMP_HOURS),
        "Total_Production_Cost",
    )

    # --- Step 6a: energy balance, one per hour ---
    # Named so the dual (shadow price) can be pulled out after solving. Spill
    # enters negatively: it is generation that did not serve demand.
    for t in HOURS:
        prob += (
            pulp.lpSum(gen[p][t] for p in PLANTS) + unserved[t] - spill[t]
            == par["demand"][t],
            "balance_{}".format(t),
        )

    # --- Step 6b: capacity, one per plant per hour ---
    for p in PLANTS:
        for t in HOURS:
            prob += (
                gen[p][t] <= par["availability"][p][t],
                "cap_{}_{}".format(p.replace(" ", "_"), t),
            )

    # --- Step 6c: ramping, one pair per plant per hour after the first ---
    # These are inequalities, so ramp_up and ramp_down are only pushed down to
    # the true movement by their cost in the objective. A plant with a zero
    # ramp premium leaves them free to sit anywhere up to the rate limit,
    # which is why the reported ramp quantities are recomputed from the
    # generation profile after solving rather than read from these variables.
    for p in PLANTS:
        for t in RAMP_HOURS:
            prev = previous[t]
            prob += (
                gen[p][t] - gen[p][prev] <= ramp_up[p][t],
                "rampup_{}_{}".format(p.replace(" ", "_"), t),
            )
            prob += (
                gen[p][prev] - gen[p][t] <= ramp_down[p][t] + forced_down[p][t],
                "rampdown_{}_{}".format(p.replace(" ", "_"), t),
            )

    # --- Step 7: solve ---
    n_vars = (len(PLANTS) * len(HOURS)          # gen
              + 2 * len(HOURS)                   # unserved, spill
              + 2 * len(PLANTS) * len(RAMP_HOURS))  # ramp up and down
    print("Solving: {} variables, {} constraints ...".format(
        n_vars, len(prob.constraints)))
    prob.solve(pulp.PULP_CBC_CMD(msg=0))

    status = pulp.LpStatus[prob.status]
    if status != "Optimal":
        raise RuntimeError(
            "Solver did not reach an optimal solution (status: {}). "
            "The all-zeros dispatch always satisfies every constraint in this "
            "model - unserved demand is priced at VoLL rather than forbidden, "
            "surplus can be spilled, and no plant has a lower bound above zero "
            "- so a feasible point always exists and this is a bug in how the "
            "LP is built rather than a problem with the input data."
            .format(status)
        )
    print("Solver status: {}\n".format(status))

    return prob, gen, unserved, spill


