# Step 8b - the merit order check
# --------------------------------------------------------------------------

def dispatch_ceiling(par, output):
    """The most each plant could have generated in each hour.

    Returns a (n_plants, n_hours) array laid out like `avail`.

    Two things cap a plant: its hourly availability, and how far it could
    climb from wherever it was in the previous hour. Hour 1 has no
    predecessor, so there only availability applies.
    """
    ceiling = np.array(par["avail"], dtype=float, copy=True)
    reachable = output[:, :-1] + par["ramp_rate_vec"][:, None]
    ceiling[:, 1:] = np.minimum(ceiling[:, 1:], reachable)
    return ceiling


def dispatch_floor(par, output):
    """The least each plant could have generated in each hour.

    The mirror of `dispatch_ceiling`. A ramp-down limit puts a floor under a
    plant: having been at some output last hour, it cannot drop further than
    its ramp rate this hour, plus whatever its own availability took away from
    underneath it.

    The floor is what makes a genuinely optimal dispatch capable of looking
    like a merit order violation, which is why `check_merit_order` needs it.
    """
    floor = np.zeros_like(par["avail"])
    floor[:, 1:] = (output[:, :-1]
                    - par["ramp_rate_vec"][:, None]
                    - par["forced_down"][:, 1:])
    return np.maximum(0.0, floor)


def check_merit_order(par, results):
    """Report where the dispatch appears to depart from merit order.

    The old invariant: in any hour, no plant may generate strictly below its
    dispatch ceiling while something strictly more expensive is generating.
    Cheap headroom must never be left unused above a running expensive plant.

    **This is a warning, not an error, and it no longer proves a bug.** That is
    a real loss of a correctness gate, so it is worth recording why it was
    given up.

    Ramping breaks the invariant in two separate ways, and both are optimal
    behaviour rather than mistakes:

    - A ramp *cost* means a cheap plant may deliberately hold back beneath a
      dearer one, because moving up this hour and back down next hour costs
      more in premium than the fuel it would save. The worked example in
      docs/ramping_semantics.md shows exactly this.
    - A ramp *down* limit puts a floor under a plant, so a cheap plant may run
      *low* now in order to be able to reach a low demand later without being
      stranded above it, spilling energy it cannot shed.

    No cheap check can tell either of those apart from a genuine modelling
    bug, because distinguishing them requires re-solving the LP. So the check
    keeps its arithmetic, drops its authority, and becomes a prompt to go and
    look rather than a proof that something is wrong.

    The floor is included so that a plant pinned above demand by its own
    ramp-down limit is not reported as "underused", which would be both wrong
    and extremely noisy.

    Equal-cost plants are not compared. Two plants on the same marginal cost
    may split output however the solver likes, and the strict comparison below
    never fires between them.
    """
    PLANTS, HOURS = par["PLANTS"], par["HOURS"]
    mc_vec = par["mc_vec"]

    # Rebuild the (n_plants, n_hours) arrays from the results table, so the
    # check is run against the numbers that were actually written out.
    output = np.array(
        [results["{} (MWh)".format(p)].to_numpy(dtype=float) for p in PLANTS])
    unserved_vec = results["Unserved Energy (MWh)"].to_numpy(dtype=float)

    ceiling = dispatch_ceiling(par, output)
    floor = dispatch_floor(par, output)

    # The comparator: the marginal cost of the most expensive thing generating
    # in each hour. Recomputed here rather than read from the Clearing Price
    # column, which is now the dual and is not any plant's marginal cost at
    # all. Using -inf when nothing is running makes the comparison vacuously
    # true, which is what it should be.
    running = output > TOL
    masked_mc = np.where(running, mc_vec[:, None], -np.inf)
    most_expensive = np.where(running.any(axis=0), masked_mc.max(axis=0), -np.inf)
    comparator = np.where(unserved_vec > TOL, VOLL, most_expensive)

    undercut = mc_vec[:, None] < comparator - TOL     # something dearer is on
    underused = output < ceiling - TOL                # and this plant has room
    pinned = output <= floor + TOL                    # but cannot go lower
    flagged = undercut & underused & ~pinned

    if not flagged.any():
        return

    headroom = ceiling - output
    # What the unused headroom would have been worth if it were free to use.
    # Under ramping this is an upper bound on any waste, not a bill: some of
    # it is legitimately forgone to avoid a ramp premium.
    value = float((headroom * (comparator - mc_vec[:, None]))[flagged].sum())

    rows = []
    for i, t_index in zip(*np.nonzero(flagged)):
        rows.append({
            "hour": HOURS[t_index],
            "plant": PLANTS[i],
            "mc": mc_vec[i],
            "gen": output[i, t_index],
            "ceiling": ceiling[i, t_index],
            "headroom": headroom[i, t_index],
            "above": describe_price_setter(par, comparator[t_index]),
        })
    rows.sort(key=lambda r: (r["hour"], r["plant"]))
    worst = max(rows, key=lambda r: r["headroom"])
    n_hours_affected = len(set(r["hour"] for r in rows))

    print("-" * 68)
    print("MERIT ORDER NOTE  ({} plant-hour(s) across {} hour(s))"
          .format(len(rows), n_hours_affected))
    print("-" * 68)
    print("  A plant generated below its ramp-adjusted ceiling while something")
    print("  more expensive was running. Under ramping this is often correct:")
    print("  holding back can be cheaper than paying to move, and a plant may")
    print("  stay low so that it can reach a low demand later. Worth a look,")
    print("  not proof of a bug.")
    print("  Cheap headroom left unused is worth at most ${:,.2f}.".format(value))
    print("")
    for r in rows[:10]:
        print("  hour {:>5}   {:<10} ${:>8.2f}/MWh   generated {:>9,.2f} of "
              "{:>9,.2f} MWh   ({:,.2f} MWh spare)   while {} was running"
              .format(r["hour"], r["plant"], r["mc"], r["gen"], r["ceiling"],
                      r["headroom"], r["above"]))
    if len(rows) > 10:
        print("  ... and {} more.".format(len(rows) - 10))
    print("")
    print("  Largest is hour {}: {} left {:,.2f} MWh unused.\n"
          .format(worst["hour"], worst["plant"], worst["headroom"]))


def describe_price_setter(par, price):
    """Name whatever is generating at `price`, for a diagnostic message."""
    if abs(price - VOLL) < TOL:
        return "unserved energy (VoLL)"
    if abs(price + SPILL_COST) < TOL:
        return "spilled energy"
    for p in par["PLANTS"]:
        if abs(par["marginal_cost"][p] - price) < TOL:
            return p
    return "something at ${:,.2f}/MWh".format(price)


