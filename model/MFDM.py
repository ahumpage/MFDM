def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description="Least-cost economic dispatch model.")
    parser.add_argument("--label", default=None,
                        help="short name for this run, used in the archive id")
    parser.add_argument("--notes", default=None,
                        help="longer description stored with the run")
    parser.add_argument("--no-archive", action="store_true",
                        help="solve and write results without archiving the run")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)

    print("\n" + "=" * 68)
    print("MY FIRST DISPATCH MODEL")
    print("=" * 68 + "\n")

    plants, fuel, demand, profile = load_data()
    print("Loaded {} plants, {} fuels, {} hours, {} profile rows.\n"
          .format(len(plants), len(fuel), len(demand), len(profile)))

    par = build_parameters(plants, fuel, demand, profile)
    if par["profiled"]:
        print("  profiled technologies: {}\n".format(
            ", ".join("{} ({})".format(p, par["technology"][p])
                      for p in sorted(par["profiled"]))))
    check_demand(par)
    check_capacity_adequacy(par)

    started = time.time()
    prob, gen, unserved = build_and_solve(par)
    solve_seconds = round(time.time() - started, 3)

    results = build_results(par, prob, gen, unserved)
    summary = build_summary(par, results)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    results_path = RESULTS_DIR / "dispatch_results.csv"
    summary_path = RESULTS_DIR / "plant_summary.csv"
    results.round(6).to_csv(results_path, index=False)
    summary.round(6).to_csv(summary_path, index=False)
    print("Results written:\n  {}\n  {}\n".format(results_path, summary_path))

    # Check the dispatch before standing behind it. This runs after the CSVs
    # are written so that a failed run still leaves the numbers on disk to
    # look at, but before archiving, so a run known to be wrong never enters
    # the archive and never gets a summary printed that implies it is fine.
    try:
        check_merit_order(par, results)
    except ValueError as exc:
        raise ValueError("{}\n\nResults were still written to {} so the "
                         "dispatch can be inspected.".format(exc, results_path))

    # Archive the run so it can be compared or restored later. A failure here
    # must not lose the results, which are already safely on disk.
    if not args.no_archive:
        try:
            manifest = runstore.archive_run(
                label=args.label, notes=args.notes,
                solver_status=pulp.LpStatus[prob.status], seconds=solve_seconds)
            git = manifest["git"]
            print("Archived as run: {}".format(manifest["id"]))
            if git.get("short"):
                print("  git {}{}   compare with:  python run_archive/runs.py diff {} latest\n"
                      .format(git["short"],
                              " (dirty)" if git.get("dirty") else "",
                              manifest["id"]))
            else:
                print("")
        except Exception as exc:                             # noqa: BLE001
            print("WARNING: could not archive this run ({}: {}). "
                  "Results were still written.\n"
                  .format(type(exc).__name__, exc))

    report(par, results, summary)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:                              # noqa: BLE001
        print("\nERROR: {}: {}".format(type(exc).__name__, exc))
        sys.exit(1)
