"""
My First Dispatch Model (MFDM)
==============================

A least-cost economic dispatch model built with PuLP.

Sets
    PLANTS  power plants
    HOURS   hour-by-hour time steps
    FUELS   fuels

Parameters
    availability[p][t]  MW that plant p can supply in hour t. Thermal plants
                        are available at nameplate around the clock; wind and
                        solar are nameplate scaled by an hourly capacity
                        factor read from profiles.csv.
    marginal_cost[p]    fuel_price / efficiency + VOM   ($/MWh)
    demand[t]           MWh required in hour t

Decision variables
    gen[p][t]           MWh generated by plant p in hour t
    unserved[t]         MWh of demand left unmet in hour t

Objective
    minimise sum over p, t of marginal_cost[p] * gen[p][t]
           + sum over t of VOLL * unserved[t]

Constraints
    energy balance  sum over p of gen[p][t] + unserved[t] == demand[t]
    capacity        gen[p][t] <= availability[p][t]

Scarcity
    Demand that no plant can cover is not an error, it is expensive. The
    `unserved` variable lets the balance always be met, priced at VOLL (the
    value of lost load), which sits far above every plant's marginal cost so
    the solver only reaches for it once all real capacity is exhausted. The
    consequence is that the energy balance can no longer be infeasible, so a
    non-optimal solver status now means a bug in the model rather than a
    problem with the data.

After solving, the hourly market clearing price is taken as the marginal cost
of the most expensive plant running in that hour, or VOLL in an hour with
unserved energy, and is cross-checked against the dual (shadow price) of the
energy balance constraint.

Reads the four CSVs in inputs/ and writes dispatch_results.csv and
plant_summary.csv into results/. Run dashboard/dashboard.py afterwards to
explore the results interactively.

Array layout
    Hourly quantities are held as numpy arrays of shape (n_plants, n_hours),
    with rows ordered by PLANTS and columns ordered by HOURS. The parameter
    dictionary carries `avail` (availability), `mc_vec` (marginal cost, one
    per plant), `demand_vec` and `profiled_mask` in this form. The older
    dict-of-dicts views (`availability`, `marginal_cost`, `demand`) are kept
    alongside them because the reporting code reads more clearly with named
    lookups; they are derived from the arrays so the two cannot drift apart.
"""

