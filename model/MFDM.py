def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description="Least-cost economic dispatch model.")
    parser.add_argument("--label", default=None,
                        help="short name for this run, used in the archive id")
    parser.add_argument("--notes", default=None,
                        help="longer description stored with the run")
    parser.add_argument("--no-archive", action="store_true",
                        help="solve and write results without archiving the run")
    parser.add_argument("--inputs", default=None,
                        help="read the four input CSVs from here instead of inputs/. "
                             "Useful for running the small worked example in "
                             "docs/ramping_semantics.md.")
    parser.add_argument("--results", default=None,
                        help="write the result CSVs here instead of results/")
    return parser.parse_args(argv)


def use_directories(inputs=None, results=None):
    """Point the model at a different pair of input and output folders.

    The paths are module-level constants because that keeps the common case,
    running the model over inputs/, entirely free of plumbing. Overriding them
    exists so that a small fixture can be solved without disturbing the real
    results, which is what the worked example in docs/ramping_semantics.md
    relies on.
    """
    global INPUTS_DIR, RESULTS_DIR, PLANTS_FILE, FUEL_FILE, DEMAND_FILE, PROFILE_FILE
    if inputs is not None:
        INPUTS_DIR = Path(inputs).resolve()
        PLANTS_FILE = INPUTS_DIR / "plants.csv"
        FUEL_FILE = INPUTS_DIR / "fuel.csv"
        DEMAND_FILE = INPUTS_DIR / "demand.csv"
        PROFILE_FILE = INPUTS_DIR / "profiles.csv"
    if results is not None:
        RESULTS_DIR = Path(results).resolve()


def main(argv=None):
    args = parse_args(argv)
    use_directories(args.inputs, args.results)

    print("\n" + "=" * 68)
    print("MY FIRST DISPATCH MODEL")
    print("=" * 68 + "\n")

    plants, fuel, demand, profile = load_data()
    print("Loaded {} plants, {} fuels, {} hours, {} profile rows.\n"
          .format(len(plants), len(fuel), len(demand), len(profile)))

    par = build_parameters(plants, fuel, demand, profile)
    if par["profiled"]:
        print("  profiled technologies: {}\n".format(
            ", ".join("{} ({})".format(p, par["technology"][p])
                      for p in sorted(par["profiled"]))))
    check_demand(par)
    check_capacity_adequacy(par)

    started = time.time()
    prob, gen, unserved, spill = build_and_solve(par)
    solve_seconds = round(time.time() - started, 3)

    results = build_results(par, prob, gen, unserved, spill)
    summary = build_summary(par, results)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    results_path = RESULTS_DIR / "dispatch_results.csv"
    summary_path = RESULTS_DIR / "plant_summary.csv"
    results.round(6).to_csv(results_path, index=False)
    summary.round(6).to_csv(summary_path, index=False)
    print("Results written:\n  {}\n  {}\n".format(results_path, summary_path))

    # Look over the dispatch before reporting on it. Under ramping this is a
    # note rather than a gate, so it neither stops the run nor blocks
    # archiving; see check_merit_order for why that authority was given up.
    check_merit_order(par, results)

    # Archive the run so it can be compared or restored later. A failure here
    # must not lose the results, which are already safely on disk. Runs over a
    # different pair of directories are not archived: the archive records the
    # state of inputs/ and results/, and a fixture run would misrepresent it.
    if args.no_archive or args.inputs or args.results:
        if args.inputs or args.results:
            print("Not archived: this run used custom input or output folders.\n")
    else:
        try:
            manifest = runstore.archive_run(
                label=args.label, notes=args.notes,
                solver_status=pulp.LpStatus[prob.status], seconds=solve_seconds)
            git = manifest["git"]
            print("Archived as run: {}".format(manifest["id"]))
            if git.get("short"):
                print("  git {}{}   compare with:  python run_archive/runs.py diff {} latest\n"
                      .format(git["short"],
                              " (dirty)" if git.get("dirty") else "",
                              manifest["id"]))
            else:
                print("")
        except Exception as exc:                             # noqa: BLE001
            print("WARNING: could not archive this run ({}: {}). "
                  "Results were still written.\n"
                  .format(type(exc).__name__, exc))

    report(par, results, summary, objective_value=pulp.value(prob.objective))


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:                              # noqa: BLE001
        print("\nERROR: {}: {}".format(type(exc).__name__, exc))
        sys.exit(1)
