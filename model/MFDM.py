"""
My First Dispatch Model (MFDM)
==============================

A least-cost economic dispatch model built with PuLP.

Sets
    PLANTS  power plants
    HOURS   hour-by-hour time steps
    FUELS   fuels

Parameters
    availability[p][t]  MW that plant p can supply in hour t. Thermal plants
                        are available at nameplate around the clock; wind and
                        solar are nameplate scaled by an hourly capacity
                        factor read from profiles.csv.
    marginal_cost[p]    fuel_price / efficiency + VOM   ($/MWh)
    ramp_rate[p]        MW the plant may move between adjacent hours
    ramp_cost[p]        premium per MWh moved, see "Ramping" below  ($/MWh)
    demand[t]           MWh required in hour t

Decision variables
    gen[p][t]           MWh generated by plant p in hour t
    unserved[t]         MWh of demand left unmet in hour t
    spill[t]            MWh generated in hour t that had to be thrown away
    ramp_up[p][t]       MWh of upward movement by plant p into hour t
    ramp_down[p][t]     MWh of downward movement by plant p into hour t

Objective
    minimise sum over p, t of marginal_cost[p] * gen[p][t]
           + sum over t of VOLL * unserved[t]
           + sum over t of SPILL_COST * spill[t]
           + sum over p, t of ramp_cost[p] * (ramp_up[p][t] + ramp_down[p][t])

Constraints
    energy balance  sum over p of gen[p][t] + unserved[t] - spill[t] == demand[t]
    capacity        gen[p][t] <= availability[p][t]
    ramp up         gen[p][t] - gen[p][t-1] <= ramp_up[p][t]
    ramp down       gen[p][t-1] - gen[p][t] <= ramp_down[p][t] + forced_down[p][t]
    ramp rate       ramp_up[p][t], ramp_down[p][t] <= ramp_rate[p]

Scarcity
    Demand that no plant can cover is not an error, it is expensive. The
    `unserved` variable lets the balance always be met, priced at VOLL (the
    value of lost load), which sits far above every plant's marginal cost so
    the solver only reaches for it once all real capacity is exhausted. The
    consequence is that the energy balance can no longer be infeasible, so a
    non-optimal solver status now means a bug in the model rather than a
    problem with the data.
Ramping
    A plant cannot jump to any output it likes from one hour to the next. Two
    things now limit it, and they pull in different directions.

    A ramp *rate* is a hard limit: `ramp_rate[p]` MW of movement per hour, in
    either direction, read straight from plants.csv. A ramp *cost* is a price
    on movement: burning fuel while changing output is less efficient than
    burning it at a steady state, so plants.csv carries a second, worse
    efficiency for the ramping case, and the premium is the difference between
    the two fuel costs,

        ramp_cost[p] = fuel_price[p] / ramp_efficiency[p]
                     - fuel_price[p] / efficiency[p]

    charged on every MWh moved. A ramped MWh is therefore charged twice: once
    at the plant's ordinary marginal cost through the `marginal_cost * gen`
    term, and again for the premium. That is what "the extra cost of a ramped
    MWh over a normal one" means.

    Hour 1 has no predecessor, so every plant starts wherever it likes free of
    charge, and the horizon does not wrap.

Spill
    A ramp *down* limit puts a floor under a plant rather than a ceiling over
    it, and a floor can force the fleet to generate more than the demand. The
    `unserved` variable only covers the opposite direction, so without a way
    to shed the surplus the model would have to hold demand artificially high.
    `spill[t]` is that way: energy that was generated and had to be thrown
    away.

    Spill is priced at SPILL_COST, deliberately *not* at VOLL. See the comment
    on the constant for why the two must differ.

    Spill is the mirror of unserved energy and should not be confused with
    Curtailment, which is renewable resource that was available and simply not
    taken. Curtailment is free and implicit; spill is priced and explicit. See
    CONTEXT.md.

Prices
    Ramping makes the objective intertemporal, and that changes what a price
    is. An extra MWh in hour t now also changes what it costs to serve t-1 and
    t+1, so the marginal cost of serving load stops being equal to any single
    plant's marginal cost.

    The model therefore reports the *dual* of the energy balance as the
    clearing price. It is the honest answer to "what would one more MWh in
    this hour cost the system", which is what a price is for.

    The old merit-order calculation survives as a diagnostic under the name
    "Highest Running Cost", which is what it always measured: who was last in
    the stack. It is not a price and must not be used as one.

    A spill hour prices *negative*: one more MWh of demand would save a MWh
    from being destroyed. This falls out of the dual without a special case.

Reads the four CSVs in inputs/ and writes dispatch_results.csv and
plant_summary.csv into results/. Run dashboard/dashboard.py afterwards to
explore the results interactively.

Array layout
    Hourly quantities are held as numpy arrays of shape (n_plants, n_hours),
    with rows ordered by PLANTS and columns ordered by HOURS. The parameter
    dictionary carries `avail` (availability), `mc_vec` (marginal cost, one
    per plant), `ramp_rate_vec`, `ramp_cost_vec`, `demand_vec` and
    `profiled_mask` in this form. The older dict-of-dicts views
    (`availability`, `marginal_cost`, `demand`) are kept alongside them
    because the reporting code reads more clearly with named lookups; they are
    derived from the arrays so the two cannot drift apart.
"""

